from app.services.verification_pipeline import VerificationPipeline, get_pipeline, provider_info

router = APIRouter(prefix="/api")


def pipeline_dep() -> VerificationPipeline:
    return get_pipeline()


def _provider(name: str | None):
    try:
        return get_llm_provider(name)
    except LLMConfigError as exc:
        raise APIError(400, "provider_not_configured", str(exc)) from exc


@router.get("/health", response_model=HealthResponse)
def health(db: Session = Depends(get_db), pipeline: VerificationPipeline = Depends(pipeline_dep)):
    s = get_settings()
    try:
        db.execute(text("SELECT 1"))
        db_health = ComponentHealth(status="ok")
    except Exception as exc:  # pragma: no cover
        db_health = ComponentHealth(status="error", detail=str(exc.__class__.__name__))
    nli_status, nli_detail = pipeline.nli.status
    nlp_status, nlp_detail = get_entity_recognizer().status
    return HealthResponse(
        status="ok" if db_health.status == "ok" else "degraded",
        llm={"default_provider": s.llm_provider, "openai_configured": bool(s.llm_api_key),
             "openai_model": s.llm_model if s.llm_api_key else None, "demo_available": True},
        nli=ComponentHealth(status=nli_status, detail=nli_detail),
        nlp=ComponentHealth(status=nlp_status, detail=nlp_detail),
        knowledge_providers=pipeline.retriever.provider_names,
        database=db_health,
    )


async def _run(db, pipeline, *, mode, question, answer, provider, gen_warnings, auto_correct, start):
    original = await pipeline.verify_text(answer)
    correction, final_answer, corrected = CorrectionInfo(), answer, None
    if auto_correct:
        correction, final_answer, corrected = await pipeline.correct(provider, answer, original)
    warnings = gen_warnings + original.warnings + (corrected.warnings if corrected else [])
    if provider is not None and provider.is_demo and mode == InputMode.GENERATE:
        warnings.insert(0, "Answer generated by the deterministic demo provider (canned response, not a real LLM).")
    run = history.save_run(
        db, mode=mode, question=question, provider=provider_info(provider) if provider else None,
        original_answer=answer, final_answer=final_answer, original=original, corrected=corrected,
        correction=correction, processing_ms=round((time.perf_counter() - start) * 1000, 1),
        warnings=list(dict.fromkeys(warnings)),
    )
    return history.to_response(run)


@router.post("/verify", response_model=RunResponse, status_code=201)
async def verify(req: VerifyRequest, db: Session = Depends(get_db),
                 pipeline: VerificationPipeline = Depends(pipeline_dep)):
    start = time.perf_counter()
    provider, warnings = _provider(None) if req.auto_correct else (None, [])
    return await _run(db, pipeline, mode=InputMode.VERIFY, question=req.question, answer=req.response_text,
                      provider=provider, gen_warnings=warnings, auto_correct=req.auto_correct, start=start)


@router.post("/generate-and-verify", response_model=RunResponse, status_code=201)
async def generate_and_verify(req: GenerateRequest, db: Session = Depends(get_db),
                              pipeline: VerificationPipeline = Depends(pipeline_dep)):
    start = time.perf_counter()
    provider, warnings = _provider(req.provider)
    try:
        answer = await provider.generate(req.question)
    except LLMProviderError as exc:
        raise APIError(502, "llm_provider_error", f"The LLM provider failed to generate an answer: {exc}") from exc
    return await _run(db, pipeline, mode=InputMode.GENERATE, question=req.question, answer=answer,
                      provider=provider, gen_warnings=warnings, auto_correct=req.auto_correct, start=start)


@router.post("/correct", response_model=RunResponse)
async def correct(req: CorrectRequest, db: Session = Depends(get_db),
                  pipeline: VerificationPipeline = Depends(pipeline_dep)):
    run = history.get_run(db, req.run_id)
    if run is None:
        raise APIError(404, "not_found", f"Verification run {req.run_id} was not found.")
    start = time.perf_counter()
    provider, warnings = _provider(req.provider)
    original = history.original_result(run)
    for c in original.claims:
        c.changed_in_correction = False
    correction, final_answer, corrected = await pipeline.correct(provider, run.original_answer, original)
    base = [w for w in (run.warnings or []) if not w.startswith("Correction")]
    all_warnings = list(dict.fromkeys(base + warnings + (corrected.warnings if corrected else [])))
    elapsed = round((time.perf_counter() - start) * 1000, 1)
    run = history.update_run_correction(db, run, final_answer, original, corrected, correction,
                                        round(run.processing_time_ms + elapsed, 1), all_warnings)
    return history.to_response(run)


@router.get("/history", response_model=list[HistoryItem])
def list_history(response: Response, limit: int = Query(50, ge=1, le=200), offset: int = Query(0, ge=0),
                 db: Session = Depends(get_db)):
    items, total = history.list_runs(db, limit, offset)
    response.headers["X-Total-Count"] = str(total)
    return items


@router.get("/history/{run_id}", response_model=RunResponse)
def get_history(run_id: int, db: Session = Depends(get_db)):
    run = history.get_run(db, run_id)
    if run is None:
        raise APIError(404, "not_found", f"Verification run {run_id} was not found.")
    return history.to_response(run)


@router.delete("/history/{run_id}", status_code=204)
def delete_history(run_id: int, db: Session = Depends(get_db)):
    if not history.delete_run(db, run_id):
        raise APIError(404, "not_found", f"Verification run {run_id} was not found.")
    return Response(status_code=204)


@router.delete("/history")
def clear_history(confirm: bool = Query(False, description="Must be true to clear all history"),
                  db: Session = Depends(get_db)):
    if not confirm:
        raise APIError(400, "confirmation_required", "Pass ?confirm=true to clear all verification history.")
    return {"deleted": history.clear_runs(db)}


@router.get("/stats", response_model=StatsResponse)
def get_stats(db: Session = Depends(get_db)):
    return history.stats(db)
